// The labor unions' committees for the Pro-Union tracker (approved 2026-11-28): every committee the FEC's committee files
// (cm, 2016 on) list with a labor organization as its connected organization (org type L), less the few labeled so that
// aren't unions (checked by hand, NOT_UNIONS). Writes public/labor-pacs.js, which public/trackers.js reads, so the site can
// tell a union's PAC by its FEC ID; the bulk-file scripts also go by the org type itself, so a union committee that's new
// since the list was made still counts there. Run it again once a year or so:
//   npm run trackers:labor                 (-- --refresh to download the committee files again)
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import readline from 'node:readline';
import {spawn} from 'node:child_process';

// (self-contained: the other bulk-file scripts load the tracker list, which reads the file this one writes)
async function* lines(zip,inner){
  const p=spawn('unzip',['-p',zip,inner]);let err='';p.stderr.on('data',d=>err+=d);
  yield* readline.createInterface({input:p.stdout,crlfDelay:Infinity});
  const code=await new Promise(res=>p.on('close',res));if(code)throw new Error(`unzip failed for ${zip}: ${err}`);
}
async function download(file,url,refresh){
  if(refresh&&fs.existsSync(file))fs.rmSync(file);
  if(!fs.existsSync(file)){console.log(`Downloading ${url}…`);const r=await fetch(url);if(!r.ok)throw new Error(`Download failed (HTTP ${r.status}) for ${url}`);fs.writeFileSync(file,Buffer.from(await r.arrayBuffer()));}
  return file;
}

const ROOT=fileURLToPath(new URL('../',import.meta.url)),OUT=path.join(ROOT,'public','labor-pacs.js');
const BASE=process.env.FEC_BULK_BASE||'https://www.fec.gov/files/bulk-downloads';
// Labeled as a labor organization's in the FEC's files, but not a union (checked 2026-11-28): the National Apartment
// Association's PAC, the Aerospace and Defense PAC, Fund for a Conservative Future, Vote to Elect Republicans Now PAC, a
// corn processors' cooperative, MACPAC, Tidewater PAC and Blue Cross Blue Shield of South Carolina's federal programs
// committee (an insurer's: Health Insurers + PBMs).
export const NOT_UNIONS=['C00113241','C00251728','C00326082','C00431403','C00526194','C00555086','C00460857','C00406850'];
// One cm.txt line -> its committee ID when the FEC lists a labor organization as its connected organization, else null.
export function laborCommittee(line){const c=String(line).split('|');return /^C\d{8}$/.test(c[0])&&c[12]==='L'&&!NOT_UNIONS.includes(c[0])?c[0]:null;}
export function laborModule(ids,{from,to}){
  return `// Generated by npm run trackers:labor (scripts/build-labor-pacs.mjs) from the FEC's committee files, ${from}–${to}: every\n`+
    `// committee with a labor organization as its connected organization, for the Pro-Union tracker. Don't edit by hand.\n`+
    `export const LABOR_PACS=${JSON.stringify([...ids].sort())};\n`+
    `// Labeled as a labor organization's by the FEC but not a union (checked by hand): never counted for Pro-Union.\n`+
    `export const NOT_UNIONS=${JSON.stringify(NOT_UNIONS)};\n`;
}
async function main(args){
  const refresh=args.includes('--refresh'),dir=path.join(ROOT,'.local','fec-bulk');fs.mkdirSync(dir,{recursive:true});
  const cfg=JSON.parse(fs.readFileSync(path.join(ROOT,'data','config.json'),'utf8')),to=Number(cfg.cycle)||2026,from=2016,ids=new Set();
  for(let y=from;y<=to;y+=2){const yy=String(y).slice(2),file=await download(path.join(dir,`cm${yy}.zip`),`${BASE}/${y}/cm${yy}.zip`,refresh);
    for await(const l of lines(file,'cm.txt')){const id=laborCommittee(l);if(id)ids.add(id);}}
  fs.writeFileSync(OUT,laborModule(ids,{from:from-1,to}));
  console.log(`Wrote public/labor-pacs.js: ${ids.size} union committees, ${from-1}–${to}.`);
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))main(process.argv.slice(2)).catch(e=>{console.error(e.message);process.exit(1);});
